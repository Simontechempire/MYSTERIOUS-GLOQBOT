FANCY_MAP = str.maketrans(
    "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz",
    "𝒜𝐵𝒞𝒟𝐸𝐹𝒢𝐻𝐼𝒥𝒦𝐿𝑀𝒩𝒪𝒫𝒬𝑅𝒮𝒯𝒰𝒱𝒲𝒳𝒴𝒵𝒶𝒷𝒸𝒹𝑒𝒻𝑔𝒽𝒾𝒿𝓀𝓁𝓂𝓃𝑜𝓅𝓆𝓇𝓈𝓉𝓊𝓋𝓌𝓍𝓎𝓏"
)


def bold(text: str) -> str:
    return text.translate(BOLD_MAP)


def italic(text: str) -> str:
    return text.translate(ITALIC_MAP)


def mono(text: str) -> str:
    return text.translate(MONO_MAP)


def fancy(text: str) -> str:
    return text.translate(FANCY_MAP)


def stylish(text: str, style: str = "bold") -> str:
    styles = {
        "bold": bold,
        "italic": italic,
        "mono": mono,
        "fancy": fancy,
    }
    return styles.get(style, bold)(text)
